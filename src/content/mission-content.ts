export const missionText: Readonly<Record<string, string>> = Object.assign(
  {},
  base,
  sol02,
  sol03,
  sol04,
  sol05,
  sol06,
  sol07,
  sol08,
  sol09,
  sol10,
);
export function resolveText(key: string): string {
  const value = missionText[key];
  if (!value) throw new TypeError(`Missing mission text: ${key}`);
  return value;
}
const catalog = getMediaCatalog();
/** Facts are transcribed from the team's source ledger, not generated by the API. */
export function resolveRealCard(
  id: string,
  state: Pick<GameState, 'solarVariant' | 'sky'>,
): AlbumCardRecord {
  const moment = catalog.realMoments[id];
  if (!moment) throw new TypeError(`Unknown real card: ${id}`);
  const photo = catalog.photos[moment.photoId];
  const factId = moment.variants?.[state.solarVariant].factId ?? moment.factId;
  const fact = facts[factId as keyof typeof facts];
  if (!fact) throw new TypeError(`Unknown fact: ${factId}`);
  return {
    id,
    eventId: moment.eventId,
    title: moment.title,
    fact: fact.text,
    sourceLabel: fact.sourceLabel,
    sourceUrl: fact.sourceUrl,
    photoSrc: photo.src,
    photoAlt: photo.altText,
    photoCredit: photo.credit,
    mediaLabel: photo.savedLabel,
    photoCaption: photo.caption,
    photoSourceUrl: photo.sourceUrl,
    observationSourceUrl:
      moment.eventId === 'solar_storm' ? state.sky?.sourceUrl : undefined,
    contextNote: [moment.contextNote, photo.contextNote]
      .filter(Boolean)
      .filter((v, i, a) => a.indexOf(v) === i)
      .join(' '),
    observationNote:
      moment.eventId === 'solar_storm' && state.sky
        ? `Mission solar input: ${state.solarVariant} · ${state.sky.source === 'live' ? 'Fetched' : state.sky.source === 'cache' ? 'Cached' : 'Saved'} · ${state.sky.observedAt ? `observed ${state.sky.observedAt} · retrieved ${state.sky.fetchedAt}` : `retrieved ${state.sky.fetchedAt}`}. The saved image is separate from these observations.`
        : undefined,
  };
}
export function resolveAlbum(state: GameState): AlbumCardRecord[] {
  return [...new Set(state.albumIds)].map((id) => resolveRealCard(id, state));
}
